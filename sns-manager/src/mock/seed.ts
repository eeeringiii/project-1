const BASE = new Date("2026-07-17T10:00:00+09:00");

function iso(offsetDays: number, hour = 19, minute = 0): string {
  const d = new Date(BASE);
  d.setDate(d.getDate() + offsetDays);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

